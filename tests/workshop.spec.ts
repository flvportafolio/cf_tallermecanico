import { test, expect } from '@playwright/test'

test('dashboard, navigation, filters and responsive layout', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Resumen del taller.' })).toBeVisible()
  await expect(page.locator('.order-card')).toHaveCount(6)
  await page.getByRole('button', { name: 'Listos 1', exact: true }).click()
  await expect(page.locator('.order-card')).toHaveCount(1)
  await expect(page.locator('.order-card')).toContainText('Nissan Kicks')
  await page.getByRole('button', { name: 'Todos 6', exact: true }).click()
  await expect(page.locator('.order-card')).toHaveCount(6)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-dashboard.png`, fullPage: true })
  for (const path of [
    '/ordenes',
    '/cotizaciones',
    '/clientes',
    '/ordenes/OT-1047',
    '/seguimiento/demo-1047',
  ]) {
    await page.goto(path)
    await expect(page.locator('h1')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await page.screenshot({ path: `artifacts/${testInfo.project.name}-tracking.png`, fullPage: true })
  expect(errors).toEqual([])
})

test('client approval is explicit, recorded and persists after reload', async ({ page }) => {
  await page.goto('/seguimiento/demo-1047')
  await page.getByRole('button', { name: /^Aprobar/ }).click()
  const dialog = page.getByRole('dialog')
  const confirm = dialog.getByRole('button', { name: 'Confirmar aprobación' })
  await expect(confirm).toBeDisabled()
  await dialog.getByLabel('Tu nombre completo').fill('Roberto Salinas')
  await expect(confirm).toBeDisabled()
  await dialog.getByRole('checkbox').check()
  await confirm.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Aprobado por Roberto Salinas', { exact: true })).toBeVisible()
  await expect(page.locator('.tracking-status')).toContainText('En reparación')
  await page.reload()
  await expect(page.getByText('Aprobado por Roberto Salinas', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Aprobar/ })).toHaveCount(0)
  await page.goto('/ordenes/OT-1047')
  await expect(page.getByText('Aprobado por Roberto Salinas', { exact: true })).toBeVisible()
  await expect(page.locator('.detail-main > section').first()).toContainText('En reparación')
})

