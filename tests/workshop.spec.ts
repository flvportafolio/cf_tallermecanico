test('navigation and dialogs support keyboard and mobile use', async ({ page }, testInfo) => {
  await page.goto('/')
  if (testInfo.project.name === 'mobile') {
    await expect(page.getByRole('navigation', { name: 'Navegación principal' })).not.toBeVisible()
    await page.getByRole('button', { name: 'Abrir navegación' }).click()
  }
  await page
    .getByRole('navigation', { name: 'Navegación principal' })
    .getByRole('link', { name: 'Órdenes de trabajo' })
    .click()
  await expect(page.getByRole('heading', { name: 'Órdenes de trabajo.' })).toBeVisible()
  await page.getByRole('button', { name: 'Nueva orden', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cerrar ventana' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Crear orden', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Cerrar ventana' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Nueva orden', exact: true })).toBeFocused()
})
